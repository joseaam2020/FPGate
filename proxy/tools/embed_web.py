#!/usr/bin/env python3
"""Turns the HTML pages of web/ into a C source, so the proxy is a single file to copy.

Usage: embed_web.py WEB_DIR OUT.c
"""
import sys

PAGES = [("login.html", "web_login"), ("dashboard.html", "web_dashboard"),
         ("certificate.html", "web_certificate")]


def main():
    web_dir, out = sys.argv[1], sys.argv[2]
    lines = ["/* Generated by tools/embed_web.py. Do not edit. */", '#include "web_assets.h"', ""]
    for fname, sym in PAGES:
        data = open(f"{web_dir}/{fname}", "rb").read()
        lines.append(f"const unsigned char {sym}[] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 16]) + ",")
        lines.append("    0};")
        lines.append(f"const unsigned {sym}_len = {len(data)};")
        lines.append("")
    open(out, "w").write("\n".join(lines))


main()

#!/usr/bin/env python3
"""Turn the softmax tables of a model package into ROM initialisation files for the attention unit.

  python accel/tools/gen_luts.py model/quant/release/e1_r7 accel/rtl

Also writes softmax_exp_rom.sv and softmax_recip_rom.sv (the same tables as ROM modules for the RTL).
Writes exp_table.hex (1025 entries, 4 hex digits, EXP[i] = round(exp(-i/64) * 65535), EXP[1024] = 0) and
recip_table.hex (256 entries, 4 hex digits, R[i] ~ 2^15 / (1 + (i + 0.5) / 256)), one value per line, as
$readmemh expects. The package is only read; its tables are the same for every block.
"""
import json
import struct
import sys
from pathlib import Path


def main():
    pkg, out = Path(sys.argv[1]), Path(sys.argv[2])
    m = json.load(open(pkg / "manifest.json"))
    t = m["tables"]
    raw = (pkg / "tables.bin").read_bytes()

    def u16(entry):
        off, n = entry["offset"], 1
        for d in entry["shape"]:
            n *= d
        return struct.unpack_from(f"<{n}H", raw, off)

    exp, rcp = u16(t["exp"]), u16(t["recip"])
    assert len(exp) == 1025 and len(rcp) == 256 and exp[1024] == 0 and exp[0] == 65535
    (out / "exp_table.hex").write_text("\n".join(f"{v:04x}" for v in exp) + "\n")
    (out / "recip_table.hex").write_text("\n".join(f"{v:04x}" for v in rcp) + "\n")
    # ROM modules (initial blocks): work the same in ModelSim and Quartus, no relative paths to resolve
    def rom(name, depth, vals, ports):
        aw = (depth - 1).bit_length()
        o = [f"// Generated by accel/tools/gen_luts.py from the model package: do not edit.",
             f"// {name}: {depth} x 16-bit ROM with {ports} read port(s), one cycle of read latency.",
             f"module {name} (", "  input  logic clk,"]
        for i in range(ports):
            o.append(f"  input  logic [{aw-1}:0] addr{i},")
            o.append(f"  output logic [15:0] q{i}" + ("," if i < ports - 1 else ""))
        o += [");", f"  (* romstyle = \"M10K\" *) logic [15:0] mem [{depth}];", "  initial begin"]
        o += [f"    mem[{i}] = 16'h{v:04x};" for i, v in enumerate(vals)]
        o += ["  end", "  always_ff @(posedge clk) begin"]
        o += [f"    q{i} <= mem[addr{i}];" for i in range(ports)]
        o += ["  end", "endmodule", ""]
        return "\n".join(o)

    (out / "softmax_exp_rom.sv").write_text(rom("softmax_exp_rom", 1025, exp, 2))
    (out / "softmax_recip_rom.sv").write_text(rom("softmax_recip_rom", 256, rcp, 1))
    print(f"exp_table.hex ({len(exp)} entries: {exp[0]} .. {exp[-2]}, 0), recip_table.hex ({len(rcp)} entries: {rcp[0]} .. {rcp[-1]}) -> {out}")


if __name__ == "__main__":
    main()
